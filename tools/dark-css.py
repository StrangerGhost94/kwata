"""Generate public/css/dark.css from public/css/app.css.

Finds every rule that hard-codes a light background or border and writes the
same rule under `html.theme-dark` with Apple's dark equivalents. Run after
changing app.css:  python3 tools/dark-css.py
"""
import re, tinycss2, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / 'public/css/app.css').read_text()

# light colour -> dark colour (backgrounds and borders only; text stays on variables)
BG = {
  '#fff': '#1C1C1E', '#ffffff': '#1C1C1E', 'white': '#1C1C1E',
  '#f2f2f7': '#000000', '#fdfcfb': '#1C1C1E', '#fafafa': '#1C1C1E', '#fbfbfd': '#1C1C1E',
  '#f7f7f9': '#2C2C2E', '#f5f5f7': '#2C2C2E', '#f2f2f5': '#2C2C2E', '#f4f4f6': '#2C2C2E', '#f6f6f8': '#2C2C2E',
  '#ececf0': '#3A3A3C', '#eaeaee': '#3A3A3C', '#ededf0': '#2C2C2E', '#e5e5ea': '#3A3A3C', '#efeff4': '#2C2C2E',
  '#f8f5f0': '#1A1B1E', '#fff7db': '#3A3108', '#fdecec': '#3B1513', '#f7f7f7': '#2C2C2E', '#eee': '#2C2C2E', '#ddd': '#3A3A3C',
}
# Areas that are dark on purpose, or brand-coloured, keep their colours.
SKIP = re.compile(r'splash|\.sp-|auth-hero|auth-shade|\.req\b|\.wm|btn-primary|btn-danger|badge|\.hero|onboard|trip-banner|sos|\.dark|glass-back|toast|plate-chip|\.veh\b|leaflet|maplibre|pin-|map-label|cam|::selection|set-swatch|sw-|ch-wa|ch-tg|admin|qr', re.I)
PROPS = ('background', 'background-color', 'background-image', 'border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right', 'box-shadow', 'outline-color')

hexre = re.compile(r'#[0-9a-fA-F]{3,6}\b|\bwhite\b')
rgbare = re.compile(r'rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\s*\)')

def darken(value, prop):
    changed = False
    def h(m):
        nonlocal changed
        k = m.group(0).lower()
        if k in BG: changed = True; return BG[k]
        return m.group(0)
    v = hexre.sub(h, value)
    if prop.startswith('background') or prop.startswith('border'):
        def r(m):
            nonlocal changed; changed = True
            return f'rgba(28,28,30,{m.group(1)})'
        v = rgbare.sub(r, v)
    return v if changed else None

out = []
def walk(rules, media=None):
    for rule in rules:
        if rule.type == 'at-rule' and rule.lower_at_keyword == 'media' and rule.content:
            walk(tinycss2.parse_rule_list(rule.content, skip_whitespace=True, skip_comments=True), tinycss2.serialize(rule.prelude).strip())
        elif rule.type == 'qualified-rule':
            sel = tinycss2.serialize(rule.prelude).strip()
            if SKIP.search(sel) or sel.startswith(':root') or 'theme-dark' in sel: continue
            decls = tinycss2.parse_declaration_list(rule.content, skip_whitespace=True, skip_comments=True)
            new = []
            for d in decls:
                if d.type != 'declaration' or d.lower_name not in PROPS: continue
                val = tinycss2.serialize(d.value).strip()
                dv = darken(val, d.lower_name)
                if dv: new.append(f'{d.lower_name}: {dv}{" !important" if d.important else ""}')
            if new:
                sels = ', '.join('html.theme-dark ' + s.strip() for s in sel.split(','))
                block = f'{sels} {{ {"; ".join(new)}; }}'
                out.append(f'@media {media} {{ {block} }}' if media else block)

walk(tinycss2.parse_stylesheet(src, skip_whitespace=True, skip_comments=True))
(ROOT / 'public/css/dark.css').write_text('/* Generated by tools/dark-css.py from app.css: dark versions of hard-coded light colours. Do not edit by hand. */\n' + '\n'.join(out) + '\n')
print(len(out), 'dark rules')
